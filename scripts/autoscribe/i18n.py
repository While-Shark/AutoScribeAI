def locale_for(language):
    """Return a bundled locale; legacy manuals without a locale stay Chinese."""
    if not language:
        return 'zh-CN'
    normalized = str(language).replace('_', '-').lower()
    if normalized == 'zh' or normalized.startswith('zh-'):
        return 'zh-CN'
    if normalized == 'en' or normalized.startswith('en-'):
        return 'en-US'
    if normalized == 'ja' or normalized.startswith('ja-'):
        return 'ja-JP'
    if normalized == 'ko' or normalized.startswith('ko-'):
        return 'ko-KR'
    # Authored content may use any language; built-in UI currently falls back to English.
    return 'en-US'


def t(language, key, **values):
    locale = locale_for(language)
    return CATALOGS[locale][key].format(**values)
